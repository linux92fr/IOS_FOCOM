fun AppLanguage.strings(): AppStrings = when (this) {
    AppLanguage.FR -> FrenchStrings
    AppLanguage.EN -> EnglishStrings
}

val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.FR }
val LocalAppStrings = staticCompositionLocalOf { FrenchStrings }

fun AppStrings.themeModeLabel(modeName: String): String = when (modeName) {
    "Light" -> themeLight
    "Dark" -> themeDark
    else -> themeSystem
}

fun AppStrings.translateStatus(rawStatus: String): String {
    if (language == AppLanguage.FR) return rawStatus
    return when (rawStatus.trim().lowercase(Locale.FRANCE)) {
        "envoyé" -> "Sent"
        "en attente réseau" -> "Pending network"
        "en attente" -> "Pending"
        "enregistré localement" -> "Saved locally"
        else -> rawStatus
    }
}

fun AppStrings.translateCategory(rawCategory: String): String {
    if (language == AppLanguage.FR) return rawCategory
    return when (rawCategory.trim().lowercase(Locale.FRANCE)) {
        "tous" -> allCategories
        "télétravail" -> "Remote Work"
        "congés" -> "Paid Leave"
        "santé" -> "Health"
        "rémunération" -> "Compensation"
        "législation" -> "Labor Law"
        "sécurité" -> "Safety"
        "négociations" -> "Negotiations"
        "accords" -> "Agreements"
        "accord" -> "Agreement"
        "vie syndicale" -> "Union Life"
        "bilan" -> "Review"
        "affiche" -> "Poster"
        "tract" -> "Leaflet"
        else -> rawCategory
    }
